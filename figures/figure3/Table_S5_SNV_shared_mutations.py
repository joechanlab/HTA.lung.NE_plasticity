"""
Table S5 - Shared mutations across tumor subtypes per patient with combined
histology.

For each patient with >=2 tumor cell types (combined histology), lists every
somatic SNV (synonymous and non-synonymous) detected by MSK-IMPACT targeted
sequencing and re-identified via variant-supporting reads in scRNA-seq, with
the mutant/total cell counts and VAF per tumor subtype, and sharing
classification (shared/partially shared/private) across subtypes (see Fig
3G, Methods).

Underlying data: SNV/SNV_shared_mutations.tsv, generated by
SNV/SNV_shared_mutations.py from MSK-IMPACT genotype calls piled up against
scRNA-seq reads (cell_type_final2 labels from the shared h5ad).
"""
import os

import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
IN_TSV = os.path.join(SCRIPT_DIR, "SNV", "SNV_shared_mutations.tsv")
OUT_CSV = os.path.join(SCRIPT_DIR, "Table_S5_shared_mutations_combined_histology.csv")

TYPE_ORDER = [
    "LUAD", "LUSC", "SCLC-A", "SCLC-N", "SCLC-P",
    "NonNE SCLC", "EMT", "FOXI1+ NonNE SCLC-N",
]

SHARING_LABELS = {
    "public": "Shared",
    "partially_shared": "Partially shared",
    "private": "Private",
}

df = pd.read_csv(IN_TSV, sep="\t")

long_rows = []
for _, row in df.iterrows():
    for t in TYPE_ORDER:
        n_total = row[f"n_total_{t}"]
        if n_total == 0:
            continue
        n_mut = row[f"n_mut_{t}"]
        long_rows.append({
            "Patient": row["patient"],
            "Tumor_subtypes_present": row["cell_types"],
            "Mutation_ID": row["mut_id"],
            "Gene": row["gene"],
            "Protein_change": row["protein_change"],
            "Driver_gene": "Yes" if row["is_driver"] else "No",
            "Sharing_classification": SHARING_LABELS[row["sharing"]],
            "N_subtypes_carrying_mutation": row["n_carrying_types"],
            "Tumor_subtype": t,
            "N_mutant_cells": int(n_mut),
            "N_total_cells": int(n_total),
            "VAF": round(n_mut / n_total, 4) if n_total else 0.0,
        })

table = pd.DataFrame(long_rows)

sharing_order = {v: i for i, v in enumerate(SHARING_LABELS.values())}
table["_sharing_sort"] = table["Sharing_classification"].map(sharing_order)
table = (
    table
    .sort_values(["Patient", "_sharing_sort", "Gene", "Tumor_subtype"])
    .drop(columns="_sharing_sort")
    .reset_index(drop=True)
)

table.to_csv(OUT_CSV, index=False)

print(
    f"Wrote {len(table)} rows across {table['Patient'].nunique()} patients "
    f"and {table['Mutation_ID'].nunique()} unique mutations"
)
print(table.groupby("Sharing_classification")["Mutation_ID"].nunique())
print(f"CSV -> {OUT_CSV}")
